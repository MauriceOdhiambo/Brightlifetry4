import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const read = p => readFileSync(new URL(p, import.meta.url), 'utf8');
const index = read('../index.html');
const portal = read('../portal.html');
const app = read('../assets/app.js');
const api = read('../api/server.js');
const publicPages = read('../public-pages.js');
const css = read('../public-reference.css');
const migration = read('../supabase/migrations/202611170001_site_content.sql');
assert.ok(index.includes('<link rel="icon" type="image/png" href="/favicon.png">'), 'Public favicon declaration missing');
assert.ok(portal.includes('<link rel="icon" type="image/png" href="/favicon.png">'), 'Portal favicon declaration missing');
assert.ok(css.includes('.sb-header{position:sticky!important;top:0!important;z-index:1200!important'), 'Public header is not sticky');
assert.ok(portal.includes("id=\"nav-websitecontent\"") && portal.includes("navigateTo('contentmanagement')"), 'Website Management navigation missing');
assert.ok(app.includes("'contentmanagement'"), 'Website Management route missing');
assert.ok(app.includes("case 'contentmanagement':") && app.includes('loadWebsiteManagementPage();'), 'Website Management route handler missing');
assert.ok(app.includes("callServer('getSiteContentAdmin'") && app.includes("callServer('saveSiteContent'"), 'Website Management does not use the secured content APIs');
assert.ok(app.includes("role!=='admin'&&role!=='super_admin'"), 'Frontend admin role gate missing');
assert.ok(api.includes("role !== 'admin' && role !== 'super_admin'"), 'Backend admin role gate missing');
assert.ok(api.includes("published = data && data.published === false ? false : true"), 'Draft publishing flag missing');
assert.ok(api.includes("&published=eq.true"), 'Public content endpoint must only return published rows');
const keys = ['projects_intro','home_hero','home_about','home_feature','water','poultry','agriculture','bike_skills','education','entrepreneurship','women','youth','financial_literacy','community_development','other','training'];
for (const key of keys) assert.ok(app.includes("['"+key+"'"), `Website manager section missing: ${key}`);
assert.ok(publicPages.includes("getPublicContentMap(['projects_intro','home_hero','home_about','home_feature'"), 'Public renderer is not loading managed home/project content');
assert.ok(migration.includes('create table if not exists public.site_content'), 'Supabase site_content migration missing');
console.log(`Website management checks passed: ${keys.length} editable content sections, admin-only API, favicon, sticky header.`);
